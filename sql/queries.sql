-- 20. Top selling book in each genre

SELECT *
FROM
(
    SELECT
        b.genre,
        b.title,
        SUM(o.quantity) AS books_sold,
        DENSE_RANK() OVER(
            PARTITION BY b.genre
            ORDER BY SUM(o.quantity) DESC
        ) AS rnk
    FROM Books b
    JOIN Orders o
    ON b.book_id=o.book_id
    GROUP BY
        b.genre,
        b.title
) ranked_books
WHERE rnk=1;


-- 21. Percentage contribution of every genre to total revenue

SELECT
    b.genre,
    ROUND(SUM(o.total_amount),2) AS revenue,
    ROUND(
        SUM(o.total_amount)*100.0/
        (SELECT SUM(total_amount) FROM Orders),
        2
    ) AS revenue_percentage
FROM Books b
JOIN Orders o
ON b.book_id=o.book_id
GROUP BY b.genre
ORDER BY revenue DESC;


-- 22. Monthly revenue trend

SELECT
    DATE_TRUNC('month',order_date) AS month,
    SUM(total_amount) AS revenue
FROM Orders
GROUP BY DATE_TRUNC('month',order_date)
ORDER BY month;


-- 23. Top 3 customers by spending

SELECT
    customer_id,
    name,
    total_spent
FROM
(
    SELECT
        c.customer_id,
        c.name,
        SUM(o.total_amount) AS total_spent,
        DENSE_RANK() OVER(
            ORDER BY SUM(o.total_amount) DESC
        ) AS rnk
    FROM Customers c
    JOIN Orders o
    ON c.customer_id=o.customer_id
    GROUP BY
        c.customer_id,
        c.name
) ranked_customers
WHERE rnk<=3;


-- 24. Customer Lifetime Value (CLV)

SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS total_orders,
    SUM(o.total_amount) AS lifetime_value,
    ROUND(AVG(o.total_amount),2) AS average_order_value
FROM Customers c
JOIN Orders o
ON c.customer_id=o.customer_id
GROUP BY
    c.customer_id,
    c.name
ORDER BY lifetime_value DESC;
