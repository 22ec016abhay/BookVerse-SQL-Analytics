-- 18. Find customers whose spending is above average

WITH customer_spending AS
(
    SELECT
        customer_id,
        SUM(total_amount) AS total_spent
    FROM Orders
    GROUP BY customer_id
)

SELECT
    customer_id,
    total_spent
FROM customer_spending
WHERE total_spent>
(
    SELECT AVG(total_spent)
    FROM customer_spending
);


-- 19. Highest revenue generating genre

WITH genre_revenue AS
(
    SELECT
        b.genre,
        SUM(o.total_amount) AS revenue
    FROM Books b
    JOIN Orders o
    ON b.book_id=o.book_id
    GROUP BY b.genre
)

SELECT *
FROM genre_revenue
ORDER BY revenue DESC
LIMIT 1;


